// These values are identifiers or examples, even when a machine translator recognizes a word.
export const preserveTranslationSource = (source: string): boolean =>
  identifiers.has(source)
  || /^[A-Z]{2}$/.test(source)
  || /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(source)
  || /^(?:Africa|America|Antarctica|Arctic|Asia|Atlantic|Australia|Europe|Indian|Pacific)\//.test(source)
  || /^(?:application|image|text)\//.test(source)
