const normalizeTechnicalTerms = (locale: LocalizedLocale, value: string) => {
  if (/https?:\/\//i.test(value)) return value

  if (locale === 'tr') {
    return value
      .replace(/AI yedek transkripsiyon/g, 'yapay zekâ ile transkripsiyon')
      .replace(/AI özetleri/g, 'yapay zekâ özetleri')
      .replace(/Yapay zeka/g, 'Yapay zekâ')
      .replace(/yapay zeka/g, 'yapay zekâ')
      .replace(/web kancaları/gi, 'Webhook’lar')
      .replace(/web kancasını/gi, 'Webhook’u')
      .replace(/web kancası/gi, 'Webhook')
      .replace(/\bwebhooks\b/gi, 'Webhook’lar')
      .replace(/\bwebhook\b/gi, 'Webhook')
  }

  if (locale === 'es') {
    return value
      .replace(/transcripción alternativa con IA/g, 'transcripción con IA')
      .replace(/ganchos web/gi, 'Webhooks')
      .replace(/\bwebhooks?\b/gi, (term) => term.toLowerCase().endsWith('s') ? 'Webhooks' : 'Webhook')
  }

  return value
    .replace(/AI 备用转录/g, 'AI 转录')
    .replace(/网络钩子/g, 'Webhook')
    .replace(/\bwebhooks?\b/gi, 'Webhook')
    .replace(/通道同步/g, '频道同步')
}

export const improvePublicTranslations = (locale: LocalizedLocale, generated: TranslationMap): TranslationMap => {
  const improved = Object.fromEntries(
    Object.entries(generated).map(([source, translated]) => [source, normalizeTechnicalTerms(locale, translated)]),
  )
  const combined = { ...improved, ...overrides[locale], ...docsTranslations(locale), ...reviewedTranslations(locale) }
  return Object.fromEntries(Object.entries(combined).map(([source, translated]) =>
    [source, preserveTranslationSource(source) ? source : normalizeTechnicalTerms(locale, translated)],
  ))
}
